def denormalize(tensor):
    """
    Denormalize image tensor for visualization.

    Args:
        tensor (np.ndarray): Normalized image tensor.

    Returns:
        np.ndarray: Denormalized image.
    """
    mean = np.array([0.485, 0.456, 0.406])
    std = np.array([0.229, 0.224, 0.225])
    tensor = tensor.transpose((1, 2, 0))
    tensor = std * tensor + mean
    return np.clip(tensor, 0, 1)

def compute_metrics(y_true, y_pred):
    """
    Compute evaluation metrics for segmentation.

    Args:
        y_true (np.ndarray): Ground truth masks.
        y_pred (np.ndarray): Predicted masks.

    Returns:
        tuple: Accuracy, IoU, and Dice coefficient.
    """
    accuracy = np.mean(y_true.flatten() == y_pred.flatten()) * 100
    y_true_sq, y_pred_sq = np.squeeze(y_true), np.squeeze(y_pred)
    intersection = np.sum(y_true_sq * y_pred_sq, axis=(1, 2))
    union = np.sum(y_true_sq, axis=(1, 2)) + np.sum(y_pred_sq, axis=(1, 2)) - intersection
    iou = np.mean(intersection / (union + 1e-6))
    dice = np.mean((2. * intersection) / (np.sum(y_true_sq, axis=(1, 2)) + np.sum(y_pred_sq, axis=(1, 2)) + 1e-6))
    return accuracy, iou, dice

def plot_segmentation_examples(images, true_masks, pred_masks, num_examples=5):
    """
    Plot segmentation examples for visualization.

    Args:
        images (np.ndarray): Input images.
        true_masks (np.ndarray): Ground truth masks.
        pred_masks (np.ndarray): Predicted masks.
        num_examples (int): Number of examples to plot.
    """
    indices = np.random.choice(len(images), num_examples, replace=False)
    for idx in indices:
        fig, axes = plt.subplots(1, 3, figsize=(15, 5))
        axes[0].imshow(denormalize(images[idx]))
        axes[0].set_title('Input Image')
        axes[0].axis('off')
        axes[1].imshow(true_masks[idx].squeeze(), cmap='gray')
        axes[1].set_title('Ground Truth')
        axes[1].axis('off')
        axes[2].imshow(pred_masks[idx].squeeze(), cmap='gray')
        axes[2].set_title('Predicted Mask')
        axes[2].axis('off')
        plt.tight_layout()
        plt.savefig(os.path.join(RESULTS_DIR, f'student_segmentation_example_{idx}.png'))
        plt.close()

