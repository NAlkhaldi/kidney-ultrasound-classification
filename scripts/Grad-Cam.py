class SingleInputDataset(Dataset):
    def __init__(self, df, transforms=None, path_col='non_seg_path'):
        self.df = df.reset_index(drop=True)
        self.transforms = transforms
        self.path_col = path_col
    def __len__(self): return len(self.df)
    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        img = np.array(Image.open(row[self.path_col]).convert("RGB"))
        if self.path_col == 'seg_path':
            kidney = np.any(img > 20, axis=-1)
            mean_color = img[kidney].mean(axis=0).astype(np.uint8) if kidney.sum() > 100 else np.array([123,117,104], np.uint8)
            img[np.all(img < 10, axis=-1)] = mean_color
        if self.transforms:
            img = self.transforms(image=img)['image']
        return img, torch.tensor(row['label_int'], dtype=torch.long)

class DualInputDataset(Dataset):
    def __init__(self, df, transforms=None):
        self.df = df.reset_index(drop=True)
        self.transforms = transforms
    def __len__(self): return len(self.df)
    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        orig = np.array(Image.open(row['non_seg_path']).convert("RGB"))
        seg = np.array(Image.open(row['seg_path']).convert("RGB"))
        kidney = np.any(seg > 20, axis=-1)
        mean_color = seg[kidney].mean(axis=0).astype(np.uint8) if kidney.sum() > 100 else np.array([123,117,104], np.uint8)
        seg[np.all(seg < 10, axis=-1)] = mean_color
        if self.transforms:
            orig = self.transforms(image=orig)['image']
            seg = self.transforms(image=seg)['image']
        return torch.cat([orig, seg], dim=0), torch.tensor(row['label_int'], dtype=torch.long)

# =============================== 6-CHANNEL PATCH ===============================
def make_dual_model(model):
    def patch(m):
        for name, child in m.named_children():
            if isinstance(child, nn.Conv2d) and child.in_channels == 3:
                new_conv = nn.Conv2d(6, child.out_channels, child.kernel_size,
                                     child.stride, child.padding, child.dilation,
                                     child.groups, child.bias is not None)
                with torch.no_grad():
                    new_conv.weight[:, :3] = child.weight.clone()
                    new_conv.weight[:, 3:] = child.weight.clone()
                    if child.bias is not None:
                        new_conv.bias.copy_(child.bias)
                setattr(m, name, new_conv)
                return
            elif len(list(child.children())) > 0:
                patch(child)
    patch(model)
    return model

# =============================== EVALUATION ===============================
def evaluate_performance(model, loader, device):
    model.eval()
    preds, labels, probs = [], [], []
    with torch.no_grad():
        for batch in loader:
            outputs = model(batch[0].to(device))
            prob = torch.softmax(outputs, dim=1)
            _, pred = torch.max(outputs, 1)
            probs.extend(prob.cpu().numpy())
            preds.extend(pred.cpu().numpy())
            labels.extend(batch[-1].cpu().numpy())
    metrics = {
        'accuracy': accuracy_score(labels, preds),
        'macro_f1': f1_score(labels, preds, average='macro'),
        'roc_auc': roc_auc_score(labels, probs, average='macro', multi_class='ovr')
    }
    return metrics, np.array(labels), np.array(preds), np.array(probs)

