# =============================== DATA PREP ===============================
# (ground-truth segmented kidneys code – unchanged)

df = pd.read_csv(ANNOTATED_CSV)
df['patient_id'] = df['US'].apply(lambda x: os.path.splitext(x)[0])
df['label_str'] = df['diagnosis'].astype(str).map({'0':'Normal','0.0':'Normal','1':'CKD','1.0':'CKD','2':'AKI','2.0':'AKI'})
df['label_int'] = df['label_str'].map({'Normal':0, 'CKD':1, 'AKI':2})
df = df.dropna(subset=['label_int']).copy()

df['non_seg_path'] = df['patient_id'].apply(lambda x: os.path.join(ANNOTATED_IMAGES_DIR, f"{x}.jpg"))
df['seg_path'] = df['patient_id'].apply(lambda x: os.path.join(ANNOTATED_SEGMENTED_KIDNEY_DIR, f"{x}.jpg"))

patient_df = df.drop_duplicates('patient_id')[['patient_id','label_int']].set_index('patient_id')
train_val_pat, test_pat = train_test_split(patient_df.index, test_size=0.20, random_state=42, stratify=patient_df['label_int'])
train_pat, val_pat = train_test_split(train_val_pat, test_size=0.15, random_state=42, stratify=patient_df.loc[train_val_pat, 'label_int'])

train_df = df[df['patient_id'].isin(train_pat)].copy()
val_df   = df[df['patient_id'].isin(val_pat)].copy()
test_df  = df[df['patient_id'].isin(test_pat)].copy()

class_counts = train_df['label_int'].value_counts().sort_index()
class_weights = 1.0 / torch.tensor(class_counts.values, dtype=torch.float32)
class_weights = class_weights / class_weights.sum() * len(class_counts)

# =============================== TRAINING ===============================
backbones = [("ResNet50","resnet50"), ("DenseNet121","densenet121"), ("EfficientNetB0","efficientnet_b0"), ("SwinTiny","swin_tiny_patch4_window7_224")]
pipelines = ["Non_Segmented", "Segmented_Only", "Dual_Input"]
CLASSES = ['Normal', 'CKD', 'AKI']

total_start = time.time()
results = []

for alias, tname in backbones:
    for ptype in pipelines:
        print(f"\n{'='*80}\n{alias} – {ptype} (Seed {SEED})\n{'='*80}")

        is_dual = ptype == "Dual_Input"
        path_col = 'seg_path' if ptype == "Segmented_Only" else 'non_seg_path'
        DatasetCls = DualInputDataset if is_dual else SingleInputDataset

        if is_dual:
            train_ds = DatasetCls(train_df, train_transforms)
            val_ds   = DatasetCls(val_df, val_test_transforms)
            test_ds  = DatasetCls(test_df, val_test_transforms)
        else:
            train_ds = DatasetCls(train_df, train_transforms, path_col)
            val_ds   = DatasetCls(val_df, val_test_transforms, path_col)
            test_ds  = DatasetCls(test_df, val_test_transforms, path_col)

        train_loader = DataLoader(train_ds, batch_size=16, shuffle=True, num_workers=0, pin_memory=PIN_MEMORY)
        val_loader   = DataLoader(val_ds, batch_size=16, shuffle=False, num_workers=0, pin_memory=PIN_MEMORY)
        test_loader  = DataLoader(test_ds, batch_size=16, shuffle=False, num_workers=0, pin_memory=PIN_MEMORY)

        model = timm.create_model(tname, pretrained=True, num_classes=3)
        if is_dual: model = make_dual_model(model)
        model.to(DEVICE)

        optimizer = optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-2)
        criterion = nn.CrossEntropyLoss(weight=class_weights.to(DEVICE))

        best_f1 = 0.0
        patience_cnt = 0

        for epoch in range(100):
            model.train()
            for batch in train_loader:
                optimizer.zero_grad()
                out = model(batch[0].to(DEVICE))
                loss = criterion(out, batch[-1].to(DEVICE))
                loss.backward()
                optimizer.step()

            val_metrics, _, _, _ = evaluate_performance(model, val_loader, DEVICE)
            if val_metrics['macro_f1'] > best_f1 + 1e-4:
                best_f1 = val_metrics['macro_f1']
                patience_cnt = 0
                torch.save(model.state_dict(), os.path.join(FINAL_RESULTS_DIR, f"{alias}_{ptype}_seed{SEED}_best.pth"))
            else:
                patience_cnt += 1
            if patience_cnt >= 20:
                break

        # Evaluate on test set
        best_model = timm.create_model(tname, pretrained=False, num_classes=3)
        if is_dual: best_model = make_dual_model(best_model)
        best_model.load_state_dict(torch.load(os.path.join(FINAL_RESULTS_DIR, f"{alias}_{ptype}_seed{SEED}_best.pth")))
        best_model.to(DEVICE)

        infer_start = time.time()
        test_metrics, labels, preds, probs = evaluate_performance(best_model, test_loader, DEVICE)
        infer_ms = (time.time() - infer_start) / len(test_df) * 1000
        params_m = sum(p.numel() for p in best_model.parameters() if p.requires_grad) / 1e6

        np.save(os.path.join(FINAL_RESULTS_DIR, f"{alias}_{ptype}_seed{SEED}_labels.npy"), labels)
        np.save(os.path.join(FINAL_RESULTS_DIR, f"{alias}_{ptype}_seed{SEED}_preds.npy"), preds)
        np.save(os.path.join(FINAL_RESULTS_DIR, f"{alias}_{ptype}_seed{SEED}_probs.npy"), probs)

        results.append({
            'Seed': SEED, 'Backbone': alias, 'Pipeline': ptype,
            'Params_M': round(params_m, 2), 'Infer_ms': round(infer_ms, 2),
            'Acc': round(test_metrics['accuracy'], 4),
            'F1': round(test_metrics['macro_f1'], 4),
            'AUC': round(test_metrics['roc_auc'], 4)
        })

        print(f"✓ {alias:12} {ptype:14} Acc: {test_metrics['accuracy']:.4f} | F1: {test_metrics['macro_f1']:.4f} | AUC: {test_metrics['roc_auc']:.4f}")

